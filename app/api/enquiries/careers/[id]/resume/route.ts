import { NextRequest, NextResponse } from 'next/server';
import connectDB from '@/lib/db.js';
import JobApplication from '@/lib/models/JobApplication.js';
import fs from 'fs';
import path from 'path';

export async function GET(
    request: NextRequest,
    context: { params: Promise<{ id: string }> | { id: string } }
) {
    try {
        await connectDB();
        const resolvedParams = await context.params;
        const id = resolvedParams?.id;

        if (!id) {
            return NextResponse.json({ error: 'Application ID is required' }, { status: 400 });
        }

        const application = await JobApplication.findById(id);
        if (!application) {
            return NextResponse.json({ error: 'Job application not found' }, { status: 404 });
        }

        const url = new URL(request.url);
        const isDownload = url.searchParams.get('download') === '1' || url.searchParams.get('download') === 'true';

        let buffer: Buffer | null = null;
        let mimeType = application.resumeMimeType || 'application/pdf';
        let originalName = application.resumeOriginalName || `${application.name.replace(/\s+/g, '_')}_Resume.pdf`;

        // 1. Check resumeData field (clean base64)
        if (application.resumeData && typeof application.resumeData === 'string' && application.resumeData.length > 50) {
            let b64 = application.resumeData;
            if (b64.includes(';base64,')) {
                const parts = b64.split(';base64,');
                mimeType = parts[0].replace('data:', '') || mimeType;
                b64 = parts[1];
            }
            buffer = Buffer.from(b64, 'base64');
        }

        // 2. Check resume field if it's a data URI
        if (!buffer && application.resume && typeof application.resume === 'string' && application.resume.startsWith('data:')) {
            const parts = application.resume.split(';base64,');
            if (parts.length === 2) {
                mimeType = parts[0].replace('data:', '') || mimeType;
                buffer = Buffer.from(parts[1], 'base64');
            }
        }

        // 3. Check if resume is a local filesystem path
        if (!buffer && application.resume && typeof application.resume === 'string' && !application.resume.startsWith('http')) {
            const potentialPaths = [
                application.resume,
                path.join(process.cwd(), application.resume),
                path.join(process.cwd(), 'public', application.resume)
            ];

            for (const p of potentialPaths) {
                if (fs.existsSync(p) && fs.statSync(p).isFile()) {
                    buffer = fs.readFileSync(p);
                    if (p.endsWith('.pdf')) mimeType = 'application/pdf';
                    else if (p.endsWith('.docx')) mimeType = 'application/vnd.openxmlformats-officedocument.wordprocessingml.document';
                    else if (p.endsWith('.txt')) mimeType = 'text/plain';
                    break;
                }
            }
        }

        // 4. Check if resume is an external URL
        if (!buffer && application.resume && application.resume.startsWith('http')) {
            return NextResponse.redirect(application.resume);
        }

        // 5. Fallback: if no binary buffer exists, generate formatted candidate profile document
        if (!buffer) {
            const textContent = `PROHOSTIX CAREERS - CANDIDATE RESUME SUMMARY
===================================================
Applicant Name: ${application.name}
Role Applied:   ${application.role}
Email:          ${application.email}
Phone:          ${application.countryCode} ${application.phoneNumber}
Location:       ${application.country}
Submission Date: ${new Date(application.createdAt).toLocaleString()}

Candidate Cover Message:
---------------------------------------------------
${application.message || 'No additional message provided.'}

Status: ${application.status.toUpperCase()}
Generated by ProHostix Admin System
`;
            buffer = Buffer.from(textContent, 'utf-8');
            mimeType = 'text/plain; charset=utf-8';
            originalName = `${application.name.replace(/\s+/g, '_')}_Summary.txt`;
        }

        const disposition = isDownload
            ? `attachment; filename="${encodeURIComponent(originalName)}"`
            : `inline; filename="${encodeURIComponent(originalName)}"`;

        return new NextResponse(new Uint8Array(buffer), {
            status: 200,
            headers: {
                'Content-Type': mimeType,
                'Content-Disposition': disposition,
                'Content-Length': buffer.length.toString(),
                'Cache-Control': 'public, max-age=3600',
            },
        });
    } catch (error: any) {
        console.error('Error streaming resume:', error);
        return NextResponse.json({ error: 'Failed to retrieve resume', details: error.message }, { status: 500 });
    }
}
